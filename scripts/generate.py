#!/usr/bin/env python3
"""Generates docker-compose.yml and toxiproxy/toxiproxy.json from teams.txt.

teams.txt is the only place where instances are listed. The output is
deterministic, and files are only rewritten when their content changes, so
running this twice is a no-op. Append new teams at the end: a team's Toxiproxy
port is 7001 + its position in the file.
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SERVER_NAME = "tactical-server"  # the name agents dial, a network alias of toxiproxy
RECEIVER_PORT = 7000
FIRST_PROXY_PORT = 7001
GCS_PORT = 4600

HEADER = """\
# GENERATED by scripts/generate.py from teams.txt. Do not edit by hand.
name: telemetry-pipeline

x-hardened: &hardened
  restart: unless-stopped
  read_only: true
  cap_drop: [ALL]
  security_opt: ["no-new-privileges:true"]
  ulimits: {core: 0}  # no core dumps: they would contain buffered locations

x-pipeline: &pipeline
  <<: *hardened
  image: telemetry-pipeline:local
  # provenance: false keeps the image id stable on Linux (see .build-stamp in the Makefile)
  build: {context: ., dockerfile: Dockerfile, provenance: false}
  user: "${HOST_UID:-1000}:${HOST_GID:-1000}"

services:
"""


def teams():
    names = []
    for line in (ROOT / "teams.txt").read_text().splitlines():
        name = line.split("#", 1)[0].strip()
        if not name:
            continue
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,30}", name):
            raise SystemExit(f"invalid team id {name!r}: use lowercase letters, digits and '-'")
        if name in names:
            raise SystemExit(f"duplicate team id {name!r}")
        names.append(name)
    if not names:
        raise SystemExit("teams.txt lists no teams")
    return names


def agent_service(name, port, team, certs, networks, profile=None):
    lines = [
        f"  {name}:",
        "    <<: *pipeline",
        "    command: [\"pipeline.agent\"]",
    ]
    if profile:
        lines += [f"    profiles: [{profile}]", "    restart: \"no\""]
    lines += [
        "    mem_limit: 128m",
        "    environment:",
        f"      AGENT_ID: {team}",
        f"      AGENT_LISTEN: 0.0.0.0:{GCS_PORT}",
        f"      AGENT_SERVER: {SERVER_NAME}:{port}",
        "      TLS_CA: /certs/ca.crt",
        "      TLS_CERT: /certs/tls.crt",
        "      TLS_KEY: /certs/tls.key",
        "    volumes:",
        f"      - ./certs/{certs}:/certs:ro",
        f"    networks: [{', '.join(networks)}]",
        "",
    ]
    return lines


def compose(names):
    out = [HEADER.rstrip("\n")]
    out += [
        "  receiver:",
        "    <<: *pipeline",
        "    command: [\"pipeline.receiver\"]",
        "    environment:",
        f"      RECEIVER_LISTEN: 0.0.0.0:{RECEIVER_PORT}",
        f"      RECEIVER_ALLOWED_IDS: {','.join(names)}",
        "      RECEIVER_DB: /data/telemetry.db",
        "      TLS_CA: /certs/ca.crt",
        "      TLS_CERT: /certs/tls.crt",
        "      TLS_KEY: /certs/tls.key",
        "    volumes:",
        "      - ./certs/server:/certs:ro",
        "      - ./data/receiver:/data",
        "    networks: [tactical]  # no published port: reachable only through toxiproxy",
        "",
        "  # Plays the internet between the instances and the tactical server.",
        "  toxiproxy:",
        "    <<: *hardened",
        "    image: ghcr.io/shopify/toxiproxy:2.12.0",
        "    command: [\"-host=0.0.0.0\", \"-config=/config/toxiproxy.json\"]",
        "    volumes:",
        "      - ./toxiproxy/toxiproxy.json:/config/toxiproxy.json:ro",
        "    ports:",
        "      - \"127.0.0.1:8474:8474\"  # API for the network scenarios, localhost only",
        "    networks:",
        f"      wan: {{aliases: [{SERVER_NAME}]}}",
        "      tactical: {}",
        "      control: {}",
        "",
    ]
    for i, team in enumerate(names):
        out += agent_service(f"agent-{team}", FIRST_PROXY_PORT + i, team, team, [f"gcs-{team}", "wan"])
        out += [
            f"  gcs-{team}:",
            "    <<: *hardened",
            "    image: telemetry-sim:local",
            "    build: {context: gcs-sim, provenance: false}",
            "    environment:",
            f"      SIM_TEAM_ID: {team}",
            f"      SIM_TARGET: agent-{team}:{GCS_PORT}",
            f"    networks: [gcs-{team}]",
            "",
        ]
    # Rejection test only (scripts/test-rogue.sh). Both dial team 1's proxy, like an
    # attacker who found the tactical server's address.
    out += agent_service("rogue-impersonator", FIRST_PROXY_PORT, names[0], "rogue-impersonator", ["wan"], "rogue")
    out += agent_service("rogue-unlisted", FIRST_PROXY_PORT, "team-unlisted", "rogue-unlisted", ["wan"], "rogue")

    out += ["networks:",
            "  # Each team's LAN: only its GCS and its agent.",
            *[f"  gcs-{team}: {{internal: true}}" for team in names],
            "  wan: {internal: true}       # instances <-> toxiproxy",
            "  tactical: {internal: true}  # toxiproxy <-> receiver",
            "  control: {}                 # publishes the toxiproxy API to the host",
            ""]
    return "\n".join(out)


def toxiproxy(names):
    proxies = [{"name": team, "listen": f"0.0.0.0:{FIRST_PROXY_PORT + i}",
                "upstream": f"receiver:{RECEIVER_PORT}", "enabled": True}
               for i, team in enumerate(names)]
    return json.dumps(proxies, indent=2) + "\n"


def write(path: pathlib.Path, content: str):
    if path.exists() and path.read_text() == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print(f"wrote {path.relative_to(ROOT)}")


def main():
    names = teams()
    write(ROOT / "docker-compose.yml", compose(names))
    write(ROOT / "toxiproxy" / "toxiproxy.json", toxiproxy(names))


if __name__ == "__main__":
    main()
